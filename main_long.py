def enforce_numbered_list(text):
    if not re.search(r"^\d+\.", text, re.M):
        sentences = re.split(r"[。！？]", text)
        lines = []
        seen = set()
        idx = 1
        for s in sentences:
            s = s.strip()
            if len(s) > 0 and s not in seen:
                lines.append(f"{idx}. {s}")
                seen.add(s)
                idx += 1
        return "\n".join(lines)
    else:
        lines = []
        seen = set()
        for line in text.splitlines():
            content = re.sub(r"^\d+\.\s*", "", line).strip()
            if content and content not in seen:
                lines.append(line)
                seen.add(content)
        return "\n".join(lines)
    
def retrieve_candidates(
    domain,
    typ, 
    basic_info,
    long_goal_text, 
    topk=6):
    """
    改良版二階段搜尋：
    1. 程式解析 ICF 障礙類別與障礙等級
    2. AI Query Planner 產生語意搜尋句
    3. full query + planner query + 原始欄位 query 多層搜尋
    4. semantic retrieval
    5. CrossEncoder rerank
    6. 障礙類別/等級符合者加權
    7. 合併分數後回傳
    """
    
    if isinstance(long_goal_text, list):
        long_goal_block = "\n".join(
            [
                f"{i+1}. {str(goal).strip()}"
                for i, goal in enumerate(long_goal_text)
                if str(goal).strip()   
            ]    
        )
    else:
        long_goal_block = str(long_goal_text or "").strip()
        
    disability_info = extract_disability_info(
       basic_info=basic_info
    )
    
    target_disability_type = disability_info.get("disability_type", "")
    target_disability_level = disability_info.get("disability_level", "")
    
    target_types = split_disability_types(target_disability_type)
    
    plan = ai_query_planner(domain=domain, basic_info=basic_info, long_goal_text = long_goal_text)
    
    planner_queries = plan.get("search_queries" , [])
    
    if not planner_queries:
        fallback = " ".join([
            domain or "",
            basic_info or "",
            long_goal_text or "",
        ]).strip()
        planner_queries = [fallback] if fallback else [] 
        
    # =========================
    # 建立完整語意 query
    # =========================

    full_query = f"""
        領域：{domain or ""}
        基本資料：{basic_info or ""}
        勾選長程目標：{long_goal_block or ""}
    """.strip()
    
    # =========================
    # 組合多層 query
    # tag 用來決定權重
    # =========================
    query_items = []
    
    if full_query:
        query_items.append(("full", full_query))
        
    for q in planner_queries:
        if q and str(q).strip():
            query_items.append(("planner", str(q).strip()))
            
    if basic_info:
        query_items.append(("basic_info", basic_info.strip()))
        
    if long_goal_block:
        query_items.append(("long_goal", long_goal_block.strip()))
        
     # =========================
     # 去除重複 query
     # =========================
        
    seen_queries = set()
    clean_query_items = []
    
    for tag, q in query_items:
        q = str(q or "").strip()
        if not q:
            continue
        
        key = (tag, q)
        if key in seen_queries:
            continue
        
        seen_queries.add(key)
        clean_query_items.append((tag, q))
        
    display_queries = [q for _, q in clean_query_items]
    query_html = render_search_queries(search_queries=display_queries)
    
    tag_weight = {
        "full": 3.0,
        "planner": 2.5,
        "long_goal":2.0,
        "basic_info":1.0
    }
        
    all_docs = []
    
    for tag, q in clean_query_items:
        docs = retrieve_hybrid_with_meta(domain=domain, typ=typ, query=q, topk=topk)
        docs = rerank_docs(query=q, docs=docs, topk=topk)
        
        q_weight = tag_weight.get(tag, 1.0)

        for d in docs:
            semantic_score = d.metadata.get("semantic_score",0)
            rerank_score = d.metadata.get("rerank_score", 0)
            
            if semantic_score < 0.7 and rerank_score < 1.0:
                continue

            rerank_score = max(min(rerank_score / 10, 1.0 ), 0)
            final_score = (semantic_score * 0.4 + rerank_score * 0.6)

            final_score *= q_weight
            
            doc_disability_type = str(d.metadata.get("disability_type", "")).strip()
            
            doc_disability_level = str(d.metadata.get("disability_level", "")).strip()
            
            doc_types = split_disability_types(doc_disability_type)
            
            disability_bonus = 1.0
            
            if target_types and doc_types:
                if any(t in doc_types for t in target_types):
                    disability_bonus *= 1.05
                    
            if (
              target_disability_level
              and doc_disability_level
              and target_disability_level == doc_disability_level  
            ):
                disability_bonus *= 1.03
            
            if(
                target_types 
                and target_disability_level
                and doc_disability_level
                and any(t in doc_types for t in target_types)
                and target_disability_level == doc_disability_level
            ):
                disability_bonus *= 1.10
            
            final_score *= disability_bonus

            d.metadata["matched_query"] = q
            d.metadata["matched_tag"] = tag
            d.metadata["target_disability_type"] = target_disability_type
            d.metadata["target_disability_level"] = target_disability_level
            d.metadata["disability_bonus"] = disability_bonus
            all_docs.append((d, final_score))
            
    doc_map = {}
    
    for d, s in all_docs:
        key = d.page_content
        
        if key not in doc_map:
            doc_map[key] = {
                "doc": d,
                "score": 0.0,
                "matched_queries":[],
                "matched_tags":[],    
            }
        doc_map[key]["score"] = max(doc_map[key]["score"],s)
        doc_map[key]["matched_queries"].append(
            d.metadata.get("matched_query", "")    
        )
        doc_map[key]["matched_tags"].append(
            d.metadata.get("matched_tag", "")    
        )
        
    sorted_docs = sorted(
        doc_map.values(), 
        key=lambda x: x["score"], 
        reverse=True
    )
    
    final_docs = []
    
    for item in sorted_docs[:topk]:
        d = item["doc"]
        d.metadata["final_score"] = float(item["score"])
        d.metadata["core_intent"] = plan.get("core_intent", "")
        d.metadata["search_focus"] = plan.get("search_focus", "")
        d.metadata["matched_queries"] = list(set(item["matched_queries"]))
        d.metadata["matched_tags"] = list(set(item["matched_tags"]))
        
        final_docs.append(d)
    
    return query_html, final_docs

