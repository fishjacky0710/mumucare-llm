def extract_icf_disability_type(text: str) -> str:
    text = str(text or "").strip()
    
    m = re.search(r"障礙類別\s*[:：]?\s*([0-9.\s、,，]+)\s*類?", text)

    if m:
        nums = re.findall(r"\d+", m.group(1))
        nums = [str(int(n)) for n in nums if 1 <= int(n) <= 8]
        if nums:
            return ",".join(sorted(set(nums), key=lambda x: int(x)))
        
    nums = re.findall(r"(?:第\s*)?0?([1-8])\s*類", text)
    if nums:
        nums = [str(int(n)) for n in nums]
        return ",".join(sorted(set(nums), key=lambda x: int(x)))
    
    found = []
    for code, keywords in ICF_DISABILITY_TYPE_MAP.items():
        for kw in keywords:
            if kw and kw in text:
                found.append(code)
                break
    if found:
        return ",".join(sorted(set(found), key=lambda x: int(x)))

    return ""

def extract_disability_level(text: str) -> str:
    text = str(text or "").strip()
    
    for lv in ["極重度", "重度", "中度", "輕度"]:
        if lv in text:
            return lv
    return ""

