    def parse_goal_lines(text:str) -> list[str]:
        goals = []
        for line in str(text or "").splitlines():
            line = line.strip()
            if not line:
                continue
        
            if "對他重要" in line or "為他重要" in line:
                continue
            if line.startswith("領域"):
                continue
            
            line = re.sub(r"^長程目標\s*\d+\s*[:：]\s*", "", line)
            line = re.sub(r"^\d+\s*[\.、]\s*", "", line)
            line = re.sub(r"^[-•]\s*", "", line)
            line = line.strip()
            if line:
                goals.append(line)
        return goals
    
    def dedupe_goals(goals: list[str]) -> list[str]:
        result = []
        seen = set()
        
        for g in goals:
            key = re.sub(r"\s+", "", g)
            if key and key not in seen:
                seen.add(key)
                result.append(g)
                
        return result
    
